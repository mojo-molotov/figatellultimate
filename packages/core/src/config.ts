/**
 * The project's configuration: one declaration of everything, as data, readable without running the app.
 *
 * Layers of core, each importing only those before it (checked by dependency-cruiser):
 *     shared ──> declarations ──> paths ──> messages ──> content ──> config
 *
 * Key design decisions:
 *     - Config is data: locales, collections and taxonomies are declared once, serializable; `define*` builders
 *       validate and freeze each part, so that an invalid declaration fails at once, where it is written.
 *     - Core throws only for an invalid configuration or a broken caller contract; every content problem is a
 *       diagnostic.
 *
 * Invariants (`config.test.ts`): every invalid configuration throws `InvalidConfigError` with what to fix.
 */
import type { Collection } from './declarations/collection.js';
import type { Locales } from './declarations/locales.js';
import type { ContentSource } from './content/ports.js';
import type { Taxonomy } from './declarations/taxonomy.js';
import type { UrlOptions } from './paths/url.js';

/** Thrown by `defineConfig` on an invalid configuration (invalid configuration is the only case where core throws). */
export class InvalidConfigError extends Error {
  override readonly name = 'InvalidConfigError';
}

/** The single declaration of a figatellu project (`figatellu.config.ts`). */
export interface FigatelluConfig {
  readonly locales: Locales;
  readonly collections: Readonly<Record<string, Collection>>;
  readonly taxonomies?: Readonly<Record<string, Taxonomy>>;
  readonly urls?: UrlOptions;
  readonly source: ContentSource;
  /** Message modules: one `<locale>.ts` per declared locale in `directory`; `runtime` types an adapter. */
  readonly messages?: MessagesOptions;
  /** Output folder of the codegen, relative POSIX path from the config file. Default: `.figatellu`. */
  readonly output?: string;
  /** The generated navigation: which collections, in which order, how deep. */
  readonly navigation?: readonly NavigationItem[];
}

/** One collection of the navigation. */
export interface NavigationItem {
  readonly collection: string;
  /** Levels of folders shown as sections; `0`: only the entries at the collection's root. */
  readonly depth: number;
  /** A message key of the app (checked against the reference messages): the collection becomes one section. */
  readonly label?: string;
  /** `false`: its sections are plain links to their page, not menus; a section without a page keeps its menu. */
  readonly menus?: boolean;
}

/**
 * Where the messages live: the folder of one module per locale, and the app's schema module.
 *
 */
export interface MessagesOptions {
  /** Relative POSIX folder from the config file. */
  readonly directory: string;
  /** The runtime adapter whose translator the generated types register. */
  readonly runtime?: 'use-intl';
  /**
   * The app's message schema, a module of the folder (e.g. `schema.ts`) spreading the generated `skeleton`.
   * figatellu never loads it: it imports the generated output.
   */
  readonly schema?: string;
}

/** First line of every generated file: the writer only ever removes files that start with it. */
export const GENERATED_HEADER = '// Generated by figatellu.';

const IDENTIFIER = /^[a-z][a-zA-Z0-9]*$/;
const DEFAULT_OUTPUT = '.figatellu';

const isRecord = (value: unknown): value is Readonly<Record<string, unknown>> =>
  typeof value === 'object' && value !== null && !Array.isArray(value);

// A declaration with its `never` return: a call narrows the checked value afterwards, no assertion needed.
function fail(problem: string): never {
  throw new InvalidConfigError(`Invalid figatellu config: ${problem}.`);
}

/** A relative POSIX folder inside the project (no absolute path, no drive, no `..`). */
const isProjectFolder = (value: unknown): value is string =>
  typeof value === 'string' &&
  value !== '' &&
  !value.startsWith('/') &&
  !/^[A-Za-z]:/.test(value) &&
  !value.includes('\\') &&
  value.split('/').every((part) => part !== '..' && part !== '');

/** Values built by core's `define*` functions are frozen: a plain object literal is not accepted in their place. */
const isFrozenRecord = (value: unknown): value is Readonly<Record<string, unknown>> =>
  isRecord(value) && Object.isFrozen(value);

/**
 * A taxonomy's content collection: declared, unmounted (its entries are shown on the term pages, never on pages of
 * their own), and keyed by term alone (an optional locale, then the slug).
 */
function contentProblem(taxonomy: string, name: string, collection: unknown): void {
  const where = `taxonomy "${taxonomy}": content "${name}"`;

  if (!isRecord(collection)) fail(`${where} is not a declared collection: declare it in \`collections\``);

  if (collection['mounted'] !== false) fail(`${where} must be unmounted: add \`mounted: false\` to the collection`);

  const grammar = collection['grammar'];
  const keyedByTerm =
    Array.isArray(grammar) &&
    grammar.every((part: unknown) => isRecord(part) && (part['kind'] === 'locale' || part['kind'] === 'slug'));

  if (!keyedByTerm) fail(`${where} must be keyed by term: its grammar is \`[locale({ optional: true }), slug()]\``);
}

function validate(config: unknown): asserts config is FigatelluConfig {
  if (!isRecord(config)) fail('the default export must be an object (use defineConfig)');

  const { locales, collections, taxonomies, source, output, messages, navigation } = config;

  if (!isFrozenRecord(locales) || !Array.isArray(locales['list'])) fail('`locales` must be made with defineLocales()');

  if (!isRecord(collections) || Object.keys(collections).length === 0)
    fail('`collections` must declare at least one collection');

  for (const [name, collection] of Object.entries(collections)) {
    if (!IDENTIFIER.test(name)) fail(`collection name "${name}" must be a camelCase identifier`);

    if (!isFrozenRecord(collection) || !Array.isArray(collection['grammar'])) {
      fail(`collection "${name}" must be made with defineCollection()`);
    }
  }

  if (taxonomies !== undefined) {
    if (!isRecord(taxonomies)) fail('`taxonomies` must be an object');

    for (const [name, taxonomy] of Object.entries(taxonomies)) {
      if (!isFrozenRecord(taxonomy) || !Array.isArray(taxonomy['terms']))
        fail(`taxonomy "${name}" must be made with defineTaxonomy()`);

      // A term page's `collection` in the mounted URLs is its taxonomy's name: never a collection's too.
      if (isRecord(taxonomy['pages']) && name in collections)
        fail(`taxonomy "${name}" has pages: it cannot share its name with a collection`);

      const content = taxonomy['content'];

      if (typeof content === 'string') contentProblem(name, content, collections[content]);
    }
  }

  if (!isRecord(source) || typeof source['directories'] !== 'function' || typeof source['documents'] !== 'function') {
    fail('`source` must implement the ContentSource port (directories() and documents())');
  }

  if (output !== undefined && !isProjectFolder(output))
    fail('`output` must be a relative POSIX folder inside the project');

  if (messages !== undefined) {
    if (!isRecord(messages) || !isProjectFolder(messages['directory'])) {
      fail('`messages.directory` must be a relative POSIX folder inside the project');
    }

    const runtime = messages['runtime'];

    if (runtime !== undefined && runtime !== 'use-intl') fail('`messages.runtime` must be "use-intl" when given');

    const schema = messages['schema'];

    if (schema !== undefined) {
      const name =
        typeof schema === 'string' && /^[^/\\]+\.ts$/.test(schema) && !schema.endsWith('.d.ts')
          ? schema.slice(0, -3)
          : fail('`messages.schema` must be a TypeScript module of the messages folder, e.g. "schema.ts"');

      if (locales['list'].includes(name)) fail(`\`messages.schema\` cannot be named after the locale "${name}"`);
    }
  }

  if (navigation !== undefined) validateNavigation(navigation, collections, messages !== undefined);
}

/**
 * The named folder levels a navigation depth reaches: a segment is one level, a rest segment all the others.
 * It reads the grammar as untrusted data: the config comes from a user file.
 */
function reachedSegments(grammar: readonly unknown[], depth: number): string[] {
  const reached: string[] = [];
  let level = 0;

  for (const part of grammar) {
    if (level >= depth) break;

    if (!isRecord(part) || typeof part['name'] !== 'string') continue;

    if (part['kind'] === 'segment') {
      reached.push(part['name']);
      level += 1;
    } else if (part['kind'] === 'rest') {
      reached.push(part['name']);
      level = depth;
    }
  }

  return reached;
}

function validateNavigation(
  navigation: unknown,
  collections: Readonly<Record<string, unknown>>,
  hasMessages: boolean,
): void {
  if (!Array.isArray(navigation)) fail('`navigation` must be a list of { collection, depth }');

  const seen = new Set<string>();

  for (const item of navigation) {
    if (!isRecord(item)) fail('`navigation` must be a list of { collection, depth }');

    const { collection: key, depth, label, menus } = item;
    const collection = typeof key === 'string' ? collections[key] : undefined;

    if (typeof key !== 'string' || !isRecord(collection) || !Array.isArray(collection['grammar']))
      fail(`navigation: unknown collection "${String(key)}"`);

    if (seen.has(key)) fail(`navigation: collection "${key}" appears twice`);

    seen.add(key);

    if (typeof depth !== 'number' || !Number.isInteger(depth) || depth < 0)
      fail(`navigation: ${key}: depth must be a whole number, 0 or more`);

    if (label !== undefined && (typeof label !== 'string' || label === ''))
      fail(`navigation: ${key}: label must be a message key`);

    if (menus !== undefined && typeof menus !== 'boolean') fail(`navigation: ${key}: menus must be a boolean`);

    const metadata = collection['metadata'];

    if (!isRecord(metadata) || metadata['title'] === undefined)
      fail(`navigation: ${key} needs \`metadata.title\`: its entries are labelled by their title`);

    const reached = reachedSegments(collection['grammar'], depth);

    if ((label !== undefined || reached.length > 0) && !hasMessages)
      fail(`navigation: ${key} needs \`messages\` (its labels are messages)`);

    const messages = isRecord(collection['messages']) ? collection['messages'] : {};

    for (const segment of reached) {
      const fields = messages[segment];

      if (!Array.isArray(fields) || !fields.includes('title'))
        fail(`navigation: ${key}: segment "${segment}" needs a "title" message (messages: { ${segment}: ['title'] })`);
    }
  }
}

/**
 * Declares the project: locales, URLs, collections, taxonomies, messages, navigation and the content source.
 *
 * @param config - The configuration, its parts built by core's `define*` functions.
 * @returns The same configuration, validated (also at runtime: it is loaded from a user file) and frozen.
 * @throws {InvalidConfigError} On an invalid configuration, e.g. a navigation item naming an unknown collection, a
 *   taxonomy with pages sharing a collection's name, a taxonomy's content that is not an unmounted collection keyed by
 *   term, a messages folder outside the project.
 *
 * @example
 * // figatellu.config.ts
 * export default defineConfig({
 *   locales: defineLocales({ list: ['fr', 'en'], default: 'fr' }),
 *   collections: { pages, blog },
 *   taxonomies: { tags, authors },
 *   messages: { directory: 'messages', schema: 'schema.ts' },
 *   source: createContentCollectionsSource({ configPath: 'content-collections.ts', projectRoot }),
 * });
 */
export function defineConfig(config: FigatelluConfig): FigatelluConfig {
  return parseConfig(config);
}

/**
 * `defineConfig` for an untrusted value, such as a config file's default export.
 *
 * @param value - Anything.
 * @returns The configuration, checked then frozen.
 * @throws {InvalidConfigError} When it is not a valid configuration.
 *
 * @example
 * const config = parseConfig((await import(configUrl)).default);
 */
export function parseConfig(value: unknown): FigatelluConfig {
  validate(value);
  const config = value;

  return Object.freeze({
    ...config,
    output: config.output ?? DEFAULT_OUTPUT,
    ...(config.navigation === undefined
      ? {}
      : {
          navigation: Object.freeze(config.navigation.map((item) => Object.freeze({ ...item }))),
        }),
  });
}
